#!/usr/bin/env node
// Generates src/config/articlePages.generated.js: the full text of every
// article in src/pages/articles/, rendered to plain HTML, for crawlers.
//
// Why: bots are routed to api/og.js and never run the SPA, so an article page
// only showed Google its intro and FAQ. Retyping 2,000 lines of article copy
// into og.js would drift the first time an article is edited, so instead this
// script RENDERS THE REAL COMPONENT with a string-building createElement:
// Header/Footer/Helmet/icons render as nothing, <Link to> becomes <a href>,
// style attributes are dropped. The article file stays the one source.
//
//   node tools/generate-article-pages.mjs          write the file
//   node tools/generate-article-pages.mjs --check  exit 1 if it is stale
//
// Runs before `vite build` (package.json) and in `npm test` (--check).
// Works under node (esbuild, which Vite ships) or bun (built-in transpiler).

// Article dates render through toLocaleDateString: pin the zone so the output
// (and --check) is the same on a laptop in KL and on the build server.
process.env.TZ = "UTC";

import fs from "fs";
import path from "path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const DIR = path.join(ROOT, "src/pages/articles");
const OUT = path.join(ROOT, "src/config/articlePages.generated.js");
const SITE = "https://xdrive.my";

async function transformJsx(src) {
  if (typeof Bun !== "undefined") {
    const t = new Bun.Transpiler({ loader: "jsx", tsconfig: { compilerOptions: { jsx: "react", jsxFactory: "h", jsxFragmentFactory: "Frag" } } });
    return t.transformSync(src);
  }
  const { transform } = await import("esbuild");
  return (await transform(src, { loader: "jsx", jsx: "transform", jsxFactory: "h", jsxFragment: "Frag" })).code;
}

const VOID = new Set(["br", "hr", "img", "meta", "link", "input"]);
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const Frag = Symbol("Frag");
const nothing = () => "";

function flat(children) {
  return children.flat(Infinity).filter((c) => c != null && c !== false && c !== true && c !== "")
    .map((c) => (typeof c === "string" && c.startsWith("\u0000") ? c.slice(1) : typeof c === "object" ? c : esc(c)))
    .join("");
}
// Rendered markup is tagged with a leading NUL so a parent can tell it from
// raw text (which must be escaped). Stripped at the top.
const raw = (s) => `\u0000${s}`;

function h(type, props, ...children) {
  props = props || {};
  if (type === Frag) return raw(flat(children));
  if (typeof type === "function") return type({ ...props, children });
  const attrs = type === "a" && props.href ? ` href="${esc(props.href)}"` : "";
  if (VOID.has(type)) return raw(`<${type}${attrs}>`);
  return raw(`<${type}${attrs}>${flat(children)}</${type}>`);
}
const Link = ({ to, children }) => h("a", { href: to.startsWith("/") ? `${SITE}${to}` : to }, children);

async function renderArticle(file) {
  const orig = fs.readFileSync(path.join(DIR, file), "utf8");
  // Every imported name that is not given a real stand-in renders as nothing
  // (icons, site chrome). Collected from the import lines themselves.
  const imported = [...orig.matchAll(/^import\s+(?:(\w+)\s*,?\s*)?(?:\{([^}]*)\})?\s*from/gm)]
    .flatMap((m) => [m[1], ...(m[2] || "").split(",")]).map((s) => (s || "").trim()).filter(Boolean);
  const src = orig.replace(/^import .*$/gm, "").replace(/export default function\s+\w+/, "function __Article");
  const js = await transformJsx(src);
  const scope = { h, Frag, React: { Fragment: Frag }, Link };
  for (const n of imported) if (!(n in scope)) scope[n] = nothing;
  const body = `${js}\nreturn { ARTICLE, FAQS: typeof FAQS === "undefined" ? [] : FAQS, jsonLd: typeof jsonLd === "undefined" ? null : jsonLd, render: __Article };`;
  const mod = new Function(...Object.keys(scope), body)(...Object.values(scope));
  let html = mod.render().replace(/^\u0000/, "");
  const main = html.match(/<main>([\s\S]*)<\/main>/);
  if (!main) throw new Error(`${file}: no <main> in rendered output`);
  html = main[1];
  return {
    slug: mod.ARTICLE.slug,
    title: mod.ARTICLE.title,
    description: mod.ARTICLE.description,
    datePublished: mod.ARTICLE.datePublished,
    dateModified: mod.ARTICLE.dateModified,
    faqs: mod.FAQS,
    jsonLd: mod.jsonLd,
    html,
  };
}

const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".jsx")).sort();
const pages = {};
for (const f of files) {
  const p = await renderArticle(f);
  pages[p.slug] = p;
}
const out = `// GENERATED by tools/generate-article-pages.mjs from src/pages/articles/*.jsx.
// Do not edit. Edit the article component, then run
//   node tools/generate-article-pages.mjs
// Read by api/og.js so crawlers get the same article a visitor reads.
export const ARTICLE_PAGES = ${JSON.stringify(pages, null, 2)};
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== out) {
    console.error("articlePages.generated.js is stale: run node tools/generate-article-pages.mjs");
    process.exit(1);
  }
  console.log(`articles: ${files.length} up to date`);
} else {
  fs.writeFileSync(OUT, out);
  console.log(`articles: wrote ${files.length} pages to ${path.relative(ROOT, OUT)}`);
}
