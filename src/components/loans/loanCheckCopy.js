export function buyerMessage(lang, { name, car, docs = [], askCcris, monthly, years, deposit }) {
  const L = lang === 'en' ? 'en' : 'ms';
  const list = docs.map((d, i) => `${i + 1}. ${MSG_DOCS[L][d] || d}`).join('\n');
  const who = String(name || '').trim();
  const est = monthly > 0;
  if (L === 'en') {
    return [
      `Hi${who ? ` ${who}` : ''}, for ${car || 'the car'} you are looking at, here is what the bank needs for the loan. Please get it all ready so we send it to the bank in one go:`,
      list,
      askCcris ? 'Before we apply, please check your CCRIS and CTOS first. If there is any late payment, tell me and we sort it out first.' : null,
      est ? `Monthly estimate: ${rm(monthly)} (${years} years, ${rm(deposit)} deposit). The bank makes the loan decision.` : 'The bank makes the loan decision.',
    ].filter(Boolean).join('\n\n');
  }
  return [
    `Salam${who ? ` ${who}` : ''}, untuk ${car || 'kereta'} yang anda minat, ini dokumen yang bank perlukan untuk loan. Sediakan semua sekali, supaya kita hantar ke bank sekali jalan:`,
    list,
    askCcris ? 'Sebelum kita apply, tolong semak CCRIS dan CTOS dulu. Kalau ada bayaran lewat, beritahu saya, kita selesaikan dulu.' : null,
    est ? `Anggaran bulanan: ${rm(monthly)} (${years} tahun, deposit ${rm(deposit)}). Keputusan loan dibuat oleh bank.` : 'Keputusan loan dibuat oleh bank.',
  ].filter(Boolean).join('\n\n');
}
